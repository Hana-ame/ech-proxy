// DefaultSystemHostsPath 返回当前操作系统的系统 hosts 文件默认路径。
func DefaultSystemHostsPath() string {
	if runtime.GOOS == "windows" {
		sysRoot := os.Getenv("SystemRoot")
		if sysRoot == "" {
			sysRoot = `C:\Windows`
		}
		return filepath.Join(sysRoot, "System32", "drivers", "etc", "hosts")
	}
	return "/etc/hosts"
}

// CollectProxyDomains 收集配置中声明的所有门户域名、原域名以及上游真实域名。
func CollectProxyDomains(cfg *Config) (originalDomains []string, portalDomains []string, wildcardSuffixes []string) {
	origSeen := make(map[string]bool)
	portalSeen := make(map[string]bool)
	suffixSeen := make(map[string]bool)

	addOrig := func(d string) {
		d = cleanHost(d)
		if d == "" || d == "reminder.moonchan.xyz" || strings.Contains(d, "*") {
			return
		}
		if IsPortalDomain(d) {
			if !portalSeen[d] {
				portalSeen[d] = true
				portalDomains = append(portalDomains, d)
			}
			return
		}
		if !origSeen[d] {
			origSeen[d] = true
			originalDomains = append(originalDomains, d)
		}
	}

	addSuffix := func(s string) {
		s = strings.ToLower(strings.TrimSpace(s))
		if !strings.HasPrefix(s, ".") {
			s = "." + s
		}
		if len(s) > 1 && !suffixSeen[s] {
			suffixSeen[s] = true
			wildcardSuffixes = append(wildcardSuffixes, s)
		}
	}

	for _, d := range DefaultPixivHosts {
		addOrig(d)
	}
	addSuffix(".pixiv.net")
	addSuffix(".pximg.net")

	if cfg != nil {
		addOrig(PortalDomain)
		for entry, uc := range cfg.Upstreams {
			if IsPortalDomain(entry) {
				if !portalSeen[entry] {
					portalSeen[entry] = true
					portalDomains = append(portalDomains, entry)
				}
			} else {
				addOrig(entry)
			}
			if uc.Mode != "direct" {
				addOrig(uc.Host)
			}
			if w := uc.Wildcard; w != nil {
				if w.UpstreamSuffix != "" {
					addSuffix(w.UpstreamSuffix)
				}
				if w.EntrySuffix != "" && !IsPortalDomain(strings.TrimPrefix(w.EntrySuffix, ".")) {
					addSuffix(w.EntrySuffix)
				}
			}
		}
	}

	sort.Strings(originalDomains)
	sort.Strings(portalDomains)
	sort.Strings(wildcardSuffixes)
	return
}

// GenerateHostsBlock 生成可写入系统 hosts 文件的完整受管文本块。
func GenerateHostsBlock(cfg *Config, targetIP string) string {
	if strings.TrimSpace(targetIP) == "" {
		targetIP = "127.0.0.1"
	}
	origDomains, portalDomains, _ := CollectProxyDomains(cfg)

	var sb strings.Builder
	sb.WriteString(HostsBlockBegin + "\n")
	sb.WriteString("# Generated by ech-proxy — DO NOT EDIT INSIDE THIS BLOCK\n")
	sb.WriteString("# Tip: Use PAC mode (http://127.0.0.1:8443/proxy.pac) to avoid editing hosts!\n")
	for _, d := range origDomains {
		sb.WriteString(fmt.Sprintf("%s %s\n", targetIP, d))
	}
	for _, d := range portalDomains {
		sb.WriteString(fmt.Sprintf("%s %s\n", targetIP, d))
	}
	sb.WriteString(HostsBlockEnd + "\n")
	return sb.String()
}

// ApplyHostsBlock 将受管的 hosts 块幂等地写入或更新到指定 hosts 文件中。
func ApplyHostsBlock(hostsPath, targetIP string, cfg *Config) error {
	if hostsPath == "" {
		hostsPath = DefaultSystemHostsPath()
	}
	existing, err := os.ReadFile(hostsPath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read hosts file %s: %w", hostsPath, err)
	}
	cleaned := stripManagedHostsBlock(string(existing))
	block := GenerateHostsBlock(cfg, targetIP)
	if cleaned != "" && !strings.HasSuffix(cleaned, "\n") {
		cleaned += "\n"
	}
	updated := cleaned + "\n" + block
	return os.WriteFile(hostsPath, []byte(updated), 0o644)
}

// RemoveHostsBlock 从指定 hosts 文件中安全移除 ech-proxy 写入的受管块。
func RemoveHostsBlock(hostsPath string) error {
	if hostsPath == "" {
		hostsPath = DefaultSystemHostsPath()
	}
	existing, err := os.ReadFile(hostsPath)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("read hosts file %s: %w", hostsPath, err)
	}
	cleaned := stripManagedHostsBlock(string(existing))
	return os.WriteFile(hostsPath, []byte(cleaned), 0o644)
}

func stripManagedHostsBlock(content string) string {
	for {
		start := strings.Index(content, HostsBlockBegin)
		if start < 0 {
			break
		}
		end := strings.Index(content[start:], HostsBlockEnd)
		if end < 0 {
			content = strings.TrimRight(content[:start], "\r\n") + "\n"
			break
		}
		after := start + end + len(HostsBlockEnd)
		for after < len(content) && (content[after] == '\r' || content[after] == '\n') {
			after++
		}
		prefix := strings.TrimRight(content[:start], "\r\n")
		suffix := content[after:]
		if prefix != "" && suffix != "" {
			content = prefix + "\n" + suffix
		} else {
			content = prefix + suffix
		}
	}
	return content
}

// GeneratePAC 生成浏览器/系统自动代理配置（PAC）脚本：
//   - 当 global=false（默认白名单模式）时：远程白名单（extraWhitelist）及配置中的目标域名通过 ech-proxy 代理（PROXY），其余所有域名直接返回 DIRECT；
//   - 当 global=true（all 模式）时：无视白名单，除本机环回与局域网外的所有网站均走 ech-proxy 代理。
func GeneratePAC(cfg *Config, proxyHostPort string, global bool, extraWhitelist ...[]string) string {
	if strings.TrimSpace(proxyHostPort) == "" {
		proxyHostPort = "127.0.0.1:8443"
	}
	origDomains, portalDomains, suffixes := CollectProxyDomains(cfg)
	exactMap := make(map[string]bool, len(origDomains)+len(portalDomains))
	suffixSeen := make(map[string]bool, len(suffixes)+1)
	var finalSuffixes []string

	addSuffix := func(s string) {
		s = strings.ToLower(strings.TrimSpace(s))
		if !strings.HasPrefix(s, ".") {
			s = "." + s
		}
		if len(s) > 1 && !suffixSeen[s] {
			suffixSeen[s] = true
			finalSuffixes = append(finalSuffixes, s)
		}
	}

	for _, d := range origDomains {
		exactMap[d] = true
	}
	for _, d := range portalDomains {
		exactMap[d] = true
	}
	for _, s := range suffixes {
		addSuffix(s)
	}
	addSuffix("." + PortalDomain)

	// 将远程白名单（黄网列表）中的域名及其子域后缀加入 PAC 代理规则（白名单 -> PROXY，其他 -> DIRECT）
	for _, list := range extraWhitelist {
		for _, raw := range list {
			d := cleanHost(strings.TrimPrefix(strings.TrimSpace(raw), "*."))
			d = strings.TrimPrefix(d, ".")
			if d != "" && strings.Contains(d, ".") {
				exactMap[d] = true
				addSuffix("." + d)
			}
		}
	}
	sort.Strings(finalSuffixes)

	exactJSON, _ := json.Marshal(exactMap)
	suffixJSON, _ := json.Marshal(finalSuffixes)
	globalStr := "false"
	if global {
		globalStr = "true"
	}

	return fmt.Sprintf(`// Generated by ech-proxy — Smart Auto-Routing PAC
var PROXY_STR = "PROXY %s; DIRECT";
var GLOBAL_MODE = %s;
var EXACT_HOSTS = %s;
var SUFFIX_RULES = %s;

function FindProxyForURL(url, host) {
  host = host.toLowerCase();
  if (isPlainHostName(host) ||
      host === "localhost" ||
      shExpMatch(host, "127.*") ||
      shExpMatch(host, "10.*") ||
      shExpMatch(host, "192.168.*") ||
      shExpMatch(host, "*.local")) {
    return "DIRECT";
  }
  if (GLOBAL_MODE) {
    return PROXY_STR;
  }
  if (EXACT_HOSTS[host]) {
    return PROXY_STR;
  }
  for (var i = 0; i < SUFFIX_RULES.length; i++) {
    var s = SUFFIX_RULES[i];
    if (host.length > s.length && host.substring(host.length - s.length) === s) {
      return PROXY_STR;
    }
  }
  return "DIRECT";
}
`, proxyHostPort, globalStr, string(exactJSON), string(suffixJSON))
}