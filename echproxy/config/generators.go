func DefaultSystemHostsPath() string {
	if runtime.GOOS == "windows" {
		sysRoot := os.Getenv("SystemRoot")
		if sysRoot == "" {
			sysRoot = `C:\Windows`
		}
		return filepath.Join(sysRoot, "System32", "drivers", "etc", "hosts")
	}
	return "/etc/hosts"
}

func CollectProxyDomains(cfg *Config) (originalDomains []string, portalDomains []string, wildcardSuffixes []string) {
	origSeen := make(map[string]bool)
	portalSeen := make(map[string]bool)
	suffixSeen := make(map[string]bool)

	addOrig := func(d string) {
		d = netdial.CleanHost(d)
		if d == "" || d == "reminder.moonchan.xyz" || strings.Contains(d, "*") {
			return
		}
		if IsPortalDomain(d) {
			if !portalSeen[d] {
				portalSeen[d] = true
				portalDomains = append(portalDomains, d)
			}
			return
		}
		if !origSeen[d] {
			origSeen[d] = true
			originalDomains = append(originalDomains, d)
		}
	}

	addSuffix := func(s string) {
		s = strings.ToLower(strings.TrimSpace(s))
		if !strings.HasPrefix(s, ".") {
			s = "." + s
		}
		if len(s) > 1 && !suffixSeen[s] {
			suffixSeen[s] = true
			wildcardSuffixes = append(wildcardSuffixes, s)
		}
	}

	for _, d := range DefaultPixivHosts {
		addOrig(d)
	}
	addSuffix(".pixiv.net")
	addSuffix(".pximg.net")

	if cfg != nil {
		upstreams, _ := cfg.Snapshot()
		addOrig(PortalDomain)
		for entry, uc := range upstreams {
			if IsPortalDomain(entry) {
				if !portalSeen[entry] {
					portalSeen[entry] = true
					portalDomains = append(portalDomains, entry)
				}
			} else {
				addOrig(entry)
			}
			if uc.Mode != "direct" {
				addOrig(uc.Host)
			}
			if w := uc.Wildcard; w != nil {
				if w.UpstreamSuffix != "" {
					addSuffix(w.UpstreamSuffix)
				}
				if w.EntrySuffix != "" && !IsPortalDomain(strings.TrimPrefix(w.EntrySuffix, ".")) {
					addSuffix(w.EntrySuffix)
				}
			}
		}
	}

	sort.Strings(originalDomains)
	sort.Strings(portalDomains)
	sort.Strings(wildcardSuffixes)
	return
}

func GenerateHostsBlock(cfg *Config, targetIP string) string {
	if strings.TrimSpace(targetIP) == "" {
		targetIP = "127.0.0.1"
	}
	origDomains, portalDomains, _ := CollectProxyDomains(cfg)

	var sb strings.Builder
	sb.WriteString(HostsBlockBegin + "\n")
	sb.WriteString("# Generated by ech-proxy — DO NOT EDIT INSIDE THIS BLOCK\n")
	for _, d := range origDomains {
		sb.WriteString(fmt.Sprintf("%s %s\n", targetIP, d))
	}
	for _, d := range portalDomains {
		sb.WriteString(fmt.Sprintf("%s %s\n", targetIP, d))
	}
	sb.WriteString(HostsBlockEnd + "\n")
	return sb.String()
}

func ApplyHostsBlock(hostsPath, targetIP string, cfg *Config) error {
	if hostsPath == "" {
		hostsPath = DefaultSystemHostsPath()
	}
	existing, err := os.ReadFile(hostsPath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read hosts file %s: %w", hostsPath, err)
	}
	cleaned := stripManagedHostsBlock(string(existing))
	block := GenerateHostsBlock(cfg, targetIP)
	if cleaned != "" && !strings.HasSuffix(cleaned, "\n") {
		cleaned += "\n"
	}
	return os.WriteFile(hostsPath, []byte(cleaned+"\n"+block), 0o644)
}

func RemoveHostsBlock(hostsPath string) error {
	if hostsPath == "" {
		hostsPath = DefaultSystemHostsPath()
	}
	existing, err := os.ReadFile(hostsPath)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("read hosts file %s: %w", hostsPath, err)
	}
	return os.WriteFile(hostsPath, []byte(stripManagedHostsBlock(string(existing))), 0o644)
}

func stripManagedHostsBlock(content string) string {
	for {
		start := strings.Index(content, HostsBlockBegin)
		if start < 0 {
			break
		}
		end := strings.Index(content[start:], HostsBlockEnd)
		if end < 0 {
			content = strings.TrimRight(content[:start], "\r\n") + "\n"
			break
		}
		after := start + end + len(HostsBlockEnd)
		for after < len(content) && (content[after] == '\r' || content[after] == '\n') {
			after++
		}
		prefix := strings.TrimRight(content[:start], "\r\n")
		suffix := content[after:]
		if prefix != "" && suffix != "" {
			content = prefix + "\n" + suffix
		} else {
			content = prefix + suffix
		}
	}
	return content
}

// GeneratePAC 生成 PAC 脚本：
//   - 与 upstream.json (Config) 完全解耦（首个参数 _ *Config 被严格忽略，绝不读取 upstream.json 或内置域名）；
//   - 严格仅使用 extraWhitelist（即 pac.txt 白名单）中的域名生成 PAC 路由规则；
//   - 当 global=true（-all 模式）时，所有非本机环回/局域网域名均走 PROXY。
func GeneratePAC(cfg *Config, proxyHostPort string, global bool, extraWhitelist ...[]string) string {
	return GeneratePACWithFallback(cfg, proxyHostPort, global, "", extraWhitelist...)
}

// FormatPACProxyString formats a raw proxy server string (e.g. "127.0.0.1:10809" or "http=127.0.0.1:10809;https=127.0.0.1:10809")
// into a standard PAC return string (e.g. "PROXY 127.0.0.1:10809; DIRECT").
func FormatPACProxyString(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return "DIRECT"
	}
	upper := strings.ToUpper(raw)
	if strings.HasPrefix(upper, "PROXY ") || strings.HasPrefix(upper, "SOCKS ") || strings.HasPrefix(upper, "SOCKS5 ") || upper == "DIRECT" {
		if !strings.HasSuffix(upper, "DIRECT") {
			return raw + "; DIRECT"
		}
		return raw
	}
	if strings.Contains(raw, "=") {
		var parts []string
		tokens := strings.Split(raw, ";")
		for _, tok := range tokens {
			tok = strings.TrimSpace(tok)
			if tok == "" {
				continue
			}
			kv := strings.SplitN(tok, "=", 2)
			if len(kv) == 2 {
				proto := strings.ToLower(strings.TrimSpace(kv[0]))
				val := strings.TrimSpace(kv[1])
				if val == "" {
					continue
				}
				switch proto {
				case "http", "https":
					parts = append(parts, "PROXY "+val)
				case "socks":
					parts = append(parts, "SOCKS5 "+val, "SOCKS "+val)
				}
			}
		}
		if len(parts) > 0 {
			parts = append(parts, "DIRECT")
			return strings.Join(parts, "; ")
		}
	}
	return "PROXY " + raw + "; DIRECT"
}

// GeneratePACWithFallback generates a PAC script that routes whitelisted domains through ech-proxy,
// and falls back non-whitelisted domains to an upstream proxy (e.g. local v2ray) if configured.
func GeneratePACWithFallback(_ *Config, proxyHostPort string, global bool, fallbackProxy string, extraWhitelist ...[]string) string {
	if strings.TrimSpace(proxyHostPort) == "" {
		proxyHostPort = "127.0.0.1:8443"
	}
	exactMap := make(map[string]bool)
	suffixSeen := make(map[string]bool)
	var finalSuffixes []string

	addSuffix := func(s string) {
		s = strings.ToLower(strings.TrimSpace(s))
		if !strings.HasPrefix(s, ".") {
			s = "." + s
		}
		if len(s) > 1 && !suffixSeen[s] {
			suffixSeen[s] = true
			finalSuffixes = append(finalSuffixes, s)
		}
	}

	for _, list := range extraWhitelist {
		for _, raw := range list {
			if d := netdial.NormalizeDomainEntry(raw); d != "" {
				exactMap[d] = true
				addSuffix("." + d)
			}
		}
	}
	sort.Strings(finalSuffixes)

	exactJSON, _ := json.Marshal(exactMap)
	suffixJSON, _ := json.Marshal(finalSuffixes)
	globalStr := "false"
	if global {
		globalStr = "true"
	}

	fallbackStr := FormatPACProxyString(fallbackProxy)
	fallbackJSON, _ := json.Marshal(fallbackStr)
	proxyStr := fmt.Sprintf("PROXY %s; %s", proxyHostPort, fallbackStr)
	proxyJSON, _ := json.Marshal(proxyStr)

	return fmt.Sprintf(`// Generated by ech-proxy — Smart Auto-Routing PAC
var FALLBACK_STR = %s;
var PROXY_STR = %s;
var GLOBAL_MODE = %s;
var EXACT_HOSTS = %s;
var SUFFIX_RULES = %s;

function FindProxyForURL(url, host) {
  if (!host) {
    return "DIRECT";
  }
  host = host.toLowerCase();
  var colonIdx = host.indexOf(":");
  if (colonIdx !== -1) {
    host = host.substring(0, colonIdx);
  }
  while (host.length > 0 && host.charAt(host.length - 1) === ".") {
    host = host.substring(0, host.length - 1);
  }
  if (isPlainHostName(host) ||
      host === "localhost" ||
      shExpMatch(host, "127.*") ||
      shExpMatch(host, "10.*") ||
      shExpMatch(host, "192.168.*") ||
      shExpMatch(host, "*.local")) {
    return "DIRECT";
  }
  if (GLOBAL_MODE) {
    return PROXY_STR;
  }
  if (EXACT_HOSTS[host]) {
    return PROXY_STR;
  }
  for (var i = 0; i < SUFFIX_RULES.length; i++) {
    var s = SUFFIX_RULES[i];
    if (host.length > s.length && host.substring(host.length - s.length) === s) {
      return PROXY_STR;
    }
  }
  return FALLBACK_STR;
}
`, string(fallbackJSON), string(proxyJSON), globalStr, string(exactJSON), string(suffixJSON))
}