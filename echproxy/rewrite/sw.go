package rewrite

import (
	"encoding/json"
	"fmt"
	"net/http"
	"strings"

	"github.com/Hana-ame/ech-proxy/echproxy/config"
)

// IsJavascriptResponse 判断上游响应是否为 JavaScript 脚本。
func IsJavascriptResponse(resp *http.Response) bool {
	ct := resp.Header.Get("Content-Type")
	if ct == "" && resp.Request != nil && resp.Request.URL != nil {
		return strings.HasSuffix(resp.Request.URL.Path, ".js")
	}
	return strings.Contains(strings.ToLower(ct), "javascript")
}

// GenerateServiceWorkerJS 根据上游配置与屏蔽列表生成前端动态拦截的 /sw.js 脚本。
func GenerateServiceWorkerJS(cfg config.UpstreamMap, portalHost, port string, blockedHosts []string) string {
	swMap := make(map[string]string)
	var rules []config.WildcardRule
	seen := make(map[string]bool)

	for entry, uc := range cfg {
		if uc.Host != "" && !strings.Contains(uc.Host, portalHost) {
			target := entry
			if port != "" && !strings.Contains(target, ":") {
				target += ":" + port
			}
			swMap[uc.Host] = target
		}
		for target, local := range uc.Rewrites {
			if strings.HasPrefix(target, ".") || strings.HasPrefix(target, "*") {
				continue
			}
			if port != "" && !strings.Contains(local, ":") {
				swMap[target] = local + ":" + port
			} else {
				swMap[target] = local
			}
		}
		if uc.Wildcard != nil {
			key := uc.Wildcard.Prefix + uc.Wildcard.UpstreamSuffix
			if !seen[key] {
				seen[key] = true
				rules = append(rules, *uc.Wildcard)
			}
		}
	}

	type jsRule struct {
		P  string `json:"p"`
		ES string `json:"es"`
		US string `json:"us"`
	}
	var jrules []jsRule
	for _, r := range rules {
		jrules = append(jrules, jsRule{P: r.Prefix, ES: r.EntrySuffix, US: r.UpstreamSuffix})
	}

	bMap, _ := json.Marshal(swMap)
	bRules, _ := json.Marshal(jrules)
	bBlock, _ := json.Marshal(blockedHosts)

	return fmt.Sprintf(`// Generated by ech-proxy
const __swMap = %s;
const __swRules = %s;
const __swBlock = %s;

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));

self.addEventListener('fetch', (e) => {
  try {
    const u = new URL(e.request.url);
    if (__swBlock.some((b) => (u.hostname + u.pathname).startsWith(b))) {
      e.respondWith(new Response('', { status: 204 }));
      return;
    }
    let p = __swMap[u.hostname];
    if (!p) {
      const h = u.hostname;
      for (const r of __swRules) {
        if (h === r.us.slice(1)) {
          p = r.p.slice(0, -1) + r.es;
          break;
        }
        if (h.endsWith(r.us)) {
          const sub = h.slice(0, -r.us.length);
          p = r.p + sub + r.es;
          break;
        }
      }
    }
    if (!p) return;
    const dest = new URL(e.request.url);
    const [pHost, pPort] = p.split(':');
    dest.hostname = pHost;
    if (pPort) dest.port = pPort;
    const req = new Request(dest.toString(), {
      method: e.request.method,
      headers: e.request.headers,
      body: e.request.body,
      mode: 'cors',
      credentials: e.request.credentials,
      cache: e.request.cache,
      redirect: 'manual',
      referrer: e.request.referrer,
      integrity: e.request.integrity,
    });
    e.respondWith(fetch(req));
  } catch (_) {}
});
`, string(bMap), string(bRules), string(bBlock))
}
